"""Session-only educational report generation for single-image inference."""

from __future__ import annotations

from datetime import datetime, timezone
from html import escape

from utils.diagnostics import ImageQualitySummary, ScreeningSummary


def build_educational_report(
    *,
    filename: str,
    model_name: str,
    score: float,
    threshold: float,
    summary: ScreeningSummary,
    quality: ImageQualitySummary,
    gradcam_layer: str,
) -> str:
    """Build a self-contained HTML report without embedding or retaining the X-ray."""
    notes = "".join(f"<li>{escape(note)}</li>" for note in quality.notes)
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>PneumoVision AI educational analysis</title>
<style>
body{{font-family:Arial,sans-serif;max-width:820px;margin:40px auto;padding:0 24px;color:#102235;line-height:1.55}}
h1,h2{{color:#07182a}} .banner{{border-left:5px solid #0ca8b8;background:#eef9fa;padding:18px;margin:24px 0}}
.grid{{display:grid;grid-template-columns:repeat(2,minmax(0,1fr));gap:12px}} .item{{border:1px solid #d8e3ea;padding:14px;border-radius:8px}}
.label{{color:#60788b;font-size:12px;text-transform:uppercase;letter-spacing:.08em}} .value{{font-size:20px;font-weight:700}}
.warning{{background:#fff7e8;border:1px solid #f2d49a;padding:16px;border-radius:8px}} small{{color:#60788b}}
</style>
</head>
<body>
<small>PNEUMOVISION AI · RESEARCH USE ONLY · Generated {generated}</small>
<h1>Educational X-ray model analysis</h1>
<div class="banner"><strong>{escape(summary.headline)}</strong><br>{escape(summary.explanation)}</div>
<div class="grid">
  <div class="item"><div class="label">Thresholded class</div><div class="value">{escape(summary.label)}</div></div>
  <div class="item"><div class="label">Raw sigmoid output</div><div class="value">{score:.4f}</div></div>
  <div class="item"><div class="label">Classification threshold</div><div class="value">{threshold:.2f}</div></div>
  <div class="item"><div class="label">Source resolution</div><div class="value">{quality.width} × {quality.height}</div></div>
</div>
<h2>Traceability</h2>
<p>Source filename: <code>{escape(filename)}</code><br>Model artifact: <code>{escape(model_name)}</code><br>Grad-CAM layer: <code>{escape(gradcam_layer)}</code></p>
<p>{escape(summary.boundary_note)}</p>
<h2>Basic technical checks</h2>
<p>Mean intensity: {quality.mean_intensity:.3f}<br>Global contrast: {quality.contrast:.3f}<br>Central 98% dynamic range: {quality.dynamic_range:.3f}</p>
<ul>{notes}</ul>
<div class="warning"><strong>Important limitation</strong><br>This report is generated by an educational research prototype. It is not a diagnosis, medical device output, radiology report, or validated lesion localization. The raw model score is not a calibrated clinical probability. A qualified clinician must interpret the original image and clinical context.</div>
<p><small>The uploaded image is not embedded in this report and is not saved by the application.</small></p>
</body>
</html>"""
